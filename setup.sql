-- 5. RPC DE ADMIN (usados por admin.html)
-- ============================================================

-- Gate del módulo admin.
create or replace function admin_check(p_admin text)
returns boolean language plpgsql security definer set search_path = public as $$
begin
  perform _require_admin(p_admin);
  return true;
exception when others then
  return false;
end $$;

-- Vista general: cuentas (sin hashes) + días sincronizados con conteo.
create or replace function admin_overview(p_admin text)
returns jsonb language plpgsql security definer set search_path = public as $$
begin
  perform _require_admin(p_admin);
  return jsonb_build_object(
    'accounts', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', a.id, 'username', a.username, 'display_name', a.display_name,
        'sectors', a.sectors, 'jurs', a.jurs, 'is_active', a.is_active,
        'expires_at', a.expires_at, 'notes', a.notes, 'created_at', a.created_at,
        'last_login', a.last_login, 'login_count', a.login_count
      ) order by a.created_at desc)
      from prospect_accounts a
    ), '[]'::jsonb),
    'dates', coalesce((
      select jsonb_agg(jsonb_build_object(
        'date', pp.date, 'count', jsonb_array_length(pp.data), 'synced_at', pp.synced_at
      ) order by pp.date desc)
      from projects_public pp
    ), '[]'::jsonb)
  );
end $$;

-- Alta de cuenta. La contraseña se guarda hasheada (no recuperable).
create or replace function admin_create_account(
  p_admin text, p_username text, p_pass text, p_display text,
  p_sectors jsonb, p_jurs jsonb, p_expires date, p_notes text
) returns jsonb language plpgsql security definer set search_path = public as $$
declare new_id bigint;
begin
  perform _require_admin(p_admin);
  if length(trim(coalesce(p_username,''))) < 3 then
    return jsonb_build_object('ok', false, 'error', 'El usuario debe tener al menos 3 caracteres');
  end if;
  if length(coalesce(p_pass,'')) < 8 then
    return jsonb_build_object('ok', false, 'error', 'La contraseña debe tener al menos 8 caracteres');
  end if;
  if exists (select 1 from prospect_accounts where lower(username) = lower(trim(p_username))) then
    return jsonb_build_object('ok', false, 'error', 'Ese usuario ya existe');
  end if;
  insert into prospect_accounts (username, pass_hash, display_name, sectors, jurs, expires_at, notes)
  values (lower(trim(p_username)), crypt(p_pass, gen_salt('bf')), coalesce(p_display,''),
          coalesce(p_sectors,'[]'::jsonb), coalesce(p_jurs,'[]'::jsonb), p_expires, coalesce(p_notes,''))
  returning id into new_id;
  return jsonb_build_object('ok', true, 'id', new_id);
end $$;

-- Actualiza una cuenta (estado completo; p_expires null = sin vencimiento).
create or replace function admin_update_account(
  p_admin text, p_id bigint, p_display text,
  p_sectors jsonb, p_jurs jsonb, p_expires date, p_active boolean, p_notes text
) returns jsonb language plpgsql security definer set search_path = public as $$
begin
  perform _require_admin(p_admin);
  update prospect_accounts set
    display_name = coalesce(p_display, display_name),
    sectors = coalesce(p_sectors, sectors),
    jurs = coalesce(p_jurs, jurs),
    expires_at = p_expires,
    is_active = coalesce(p_active, is_active),
    notes = coalesce(p_notes, notes)
  where id = p_id;
  if not found then return jsonb_build_object('ok', false, 'error', 'Cuenta no encontrada'); end if;
  return jsonb_build_object('ok', true);
end $$;

-- Resetea la contraseña de una cuenta.
create or replace function admin_reset_password(p_admin text, p_id bigint, p_new_pass text)
returns jsonb language plpgsql security definer set search_path = public as $$
begin
  perform _require_admin(p_admin);
  if length(coalesce(p_new_pass,'')) < 8 then
    return jsonb_build_object('ok', false, 'error', 'La contraseña debe tener al menos 8 caracteres');
  end if;
  update prospect_accounts set pass_hash = crypt(p_new_pass, gen_salt('bf')) where id = p_id;
  if not found then return jsonb_build_object('ok', false, 'error', 'Cuenta no encontrada'); end if;
  return jsonb_build_object('ok', true);
end $$;

-- Elimina una cuenta.
create or replace function admin_delete_account(p_admin text, p_id bigint)
returns jsonb language plpgsql security definer set search_path = public as $$
begin
  perform _require_admin(p_admin);
  delete from prospect_accounts where id = p_id;
  return jsonb_build_object('ok', true);
end $$;

-- Sincroniza los proyectos de UN día (upsert por fecha) y limpia lo más viejo de 45 días.
create or replace function admin_sync_projects(p_admin text, p_date date, p_data jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
begin
  perform _require_admin(p_admin);
  insert into projects_public (date, data, synced_at)
  values (p_date, coalesce(p_data,'[]'::jsonb), now())
  on conflict (date) do update set data = excluded.data, synced_at = now();
  delete from projects_public where date < current_date - 45;
  return jsonb_build_object('ok', true, 'count', jsonb_array_length(coalesce(p_data,'[]'::jsonb)));
end $$;
