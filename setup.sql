-- ============================================================
-- 3. HELPERS INTERNOS (no expuestos)
-- ============================================================

-- Valida la contraseña de admin. Lanza excepción si no coincide.
create or replace function _require_admin(p_admin text)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not exists (
    select 1 from admin_settings
    where id = 1 and admin_hash = crypt(coalesce(p_admin,''), admin_hash)
  ) then
    raise exception 'admin_unauthorized';
  end if;
end $$;
revoke execute on function _require_admin(text) from public, anon, authenticated;

-- Valida credenciales de prospecto. Devuelve la cuenta o null.
create or replace function _prospect_auth(p_user text, p_pass text)
returns prospect_accounts language plpgsql security definer set search_path = public as $$
declare acc prospect_accounts;
begin
  select * into acc from prospect_accounts
  where lower(username) = lower(trim(coalesce(p_user,'')));
  if acc.id is null or acc.pass_hash <> crypt(coalesce(p_pass,''), acc.pass_hash) then
    return null;
  end if;
  return acc;
end $$;
revoke execute on function _prospect_auth(text, text) from public, anon, authenticated;

-- ============================================================
-- 4. RPC DE PROSPECTOS (usados por index.html)
-- ============================================================

-- Login: valida usuario+contraseña, estado y vencimiento. Registra el ingreso.
create or replace function prospect_login(p_user text, p_pass text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare acc prospect_accounts;
begin
  acc := _prospect_auth(p_user, p_pass);
  if acc.id is null then
    return jsonb_build_object('ok', false, 'reason', 'credenciales');
  end if;
  if not acc.is_active then
    return jsonb_build_object('ok', false, 'reason', 'inactiva');
  end if;
  if acc.expires_at is not null and acc.expires_at < current_date then
    return jsonb_build_object('ok', false, 'reason', 'vencida');
  end if;
  update prospect_accounts
    set last_login = now(), login_count = login_count + 1
    where id = acc.id;
  return jsonb_build_object(
    'ok', true,
    'display_name', acc.display_name,
    'sectors', acc.sectors,
    'jurs', acc.jurs,
    'expires_at', acc.expires_at
  );
end $$;

-- Proyectos visibles para la cuenta: últimos 30 días, filtrados por sector y
-- jurisdicción EN EL SERVIDOR (el prospecto nunca recibe lo que no le corresponde).
create or replace function prospect_projects(p_user text, p_pass text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare acc prospect_accounts;
begin
  acc := _prospect_auth(p_user, p_pass);
  if acc.id is null or not acc.is_active
     or (acc.expires_at is not null and acc.expires_at < current_date) then
    return jsonb_build_object('ok', false);
  end if;
  return jsonb_build_object('ok', true, 'days', coalesce((
    select jsonb_agg(jsonb_build_object('date', t.d, 'data', t.flt) order by t.d desc)
    from (
      select pp.date as d,
        (select coalesce(jsonb_agg(e), '[]'::jsonb)
           from jsonb_array_elements(pp.data) e
          where (acc.sectors = '[]'::jsonb or acc.sectors ? (e->>'sector'))
            and (acc.jurs    = '[]'::jsonb or acc.jurs    ? (e->>'jur'))
        ) as flt
      from projects_public pp
      where pp.date >= current_date - 30
    ) t
    where jsonb_array_length(t.flt) > 0
  ), '[]'::jsonb));
end $$;

