-- Cómo usar: en el dashboard de Supabase del proyecto nuevo → SQL Editor →
-- pegar TODO este archivo → antes de correrlo, CAMBIAR la contraseña de admin
-- en la línea marcada con  >>> CAMBIAR <<<  (al final de la sección 2) → Run.
--
-- Modelo de seguridad:
--   * RLS habilitado en todas las tablas y SIN policies para anon
--     → la clave pública (anon) NO puede leer ni escribir ninguna tabla directamente.
--   * Todo el acceso pasa por funciones RPC SECURITY DEFINER que validan
--     credenciales (bcrypt vía pgcrypto) en cada llamada.
--   * Las contraseñas se guardan hasheadas. No se pueden recuperar, solo resetear.
-- ============================================================

create extension if not exists pgcrypto;

-- ============================================================
-- 1. TABLAS
-- ============================================================

-- Proyectos de ley publicados a prospectos. Una fila por día de reporte.
-- Mismo formato de `data` que la tabla `projects` interna (array JSON de proyectos).
-- NUNCA contiene calificaciones de impacto ni nombres de clientes.
create table if not exists projects_public (
  id bigint generated by default as identity primary key,
  date date not null unique,
  data jsonb not null default '[]'::jsonb,
  synced_at timestamptz not null default now()
);

-- Cuentas de potenciales clientes.
create table if not exists prospect_accounts (
  id bigint generated by default as identity primary key,
  username text not null unique,
  pass_hash text not null,
  display_name text not null default '',      -- nombre de la empresa / contacto (se muestra en la app)
  sectors jsonb not null default '[]'::jsonb, -- lista de sectores permitidos; [] = todos
  jurs jsonb not null default '[]'::jsonb,    -- lista de jurisdicciones permitidas; [] = todas
  is_active boolean not null default true,
  expires_at date,                            -- null = sin vencimiento
  notes text not null default '',
  created_at timestamptz not null default now(),
  last_login timestamptz,
  login_count int not null default 0
);

-- Contraseña del módulo de administración (una sola fila).
create table if not exists admin_settings (
  id int primary key default 1,
  admin_hash text not null
);

-- RLS cerrado: sin policies → anon no toca nada directo.
alter table projects_public   enable row level security;
alter table prospect_accounts enable row level security;
alter table admin_settings    enable row level security;
revoke all on projects_public, prospect_accounts, admin_settings from anon, authenticated;

